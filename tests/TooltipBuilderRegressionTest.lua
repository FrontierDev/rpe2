local function assertEqual(actual, expected, message)
    if actual ~= expected then
        error(("%s: expected %s, got %s"):format(message, tostring(expected), tostring(actual)), 2)
    end
end

local function assertTrue(value, message)
    if value ~= true then error(message, 2) end
end

local Addon = {
    Client = {
        Spellcasting = {
            AuraManager = {
                ResolveEffectAmount = function(_, _, effect, baseField)
                    return tonumber(effect[baseField]) or 0
                end,
            },
        },
    },
    Internal = {
        Database = {
            Dependecies = {},
        },
        Comms = {
            ResourceSync = {},
        },
        Profile = {},
        Registry = {},
    },
    Utils = {
        Common = {
            Round = function(value) return math.floor((tonumber(value) or 0) + 0.5) end,
        },
    },
}

local function loadAddonFile(path)
    local chunk, loadError = loadfile(path)
    assert(chunk, loadError)
    chunk("RPEngine2", Addon)
end

loadAddonFile("client/spellcasting/TooltipTemplate.lua")
loadAddonFile("client/spellcasting/AuraDescriptionBuilder.lua")

local aura = {
    effects = {
        {
            baseAmount = 30,
            operation = "percent",
            statRef = "Threat",
            type = "stat",
        },
    },
}
local payload = {
    bodyText = "Increases Threat Generated by {AURA_STAT_1}%.",
    bodyTokens = {
        {
            applyMode = "stat_amount",
            baseField = "baseAmount",
            effectIndex = 1,
            key = "AURA_STAT_1",
            tokenType = "aura_amount",
        },
    },
    stackingText = "",
    stackingTokens = {},
}

local rendered, renderError = Addon.Client.Spellcasting.AuraDescriptionBuilder:ResolveTooltipTemplatePayload(aura, payload, {})
assertTrue(rendered ~= nil, renderError or "Aura tooltip rendering failed")
assertEqual(rendered, "Increases Threat Generated by 30%.", "percentage aura token rendering")
local _, percentCount = rendered:gsub("%%", "")
assertEqual(percentCount, 1, "percentage aura token does not duplicate percent signs")

local markOfBlood = {
    name = "Mark of Blood",
    effects = {},
    events = {
        {
            chance = 100,
            combatEventId = "on_melee_hit",
            triggerTarget = "event_other",
            effects = {
                {
                    amountMode = "max_percent",
                    baseHealing = 2,
                    type = "heal",
                },
            },
        },
    },
}

Addon.Client.Spellcasting.AuraManager.ResolveEffectAmount = function()
    return 0
end

local markDescription = Addon.Client.Spellcasting.AuraDescriptionBuilder:BuildGeneratedDescription(markOfBlood, {})
assertTrue(markDescription:find("2%% of Max", 1, false) ~= nil, "Mark of Blood matches Judgement of the Light healing")
assertTrue(markDescription:find("0%% of Max", 1, false) == nil, "Mark of Blood does not render zero percentage healing")

print("TooltipBuilderRegressionTest passed")
